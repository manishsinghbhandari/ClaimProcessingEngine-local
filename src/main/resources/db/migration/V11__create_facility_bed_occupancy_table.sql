
CREATE TABLE IF NOT EXISTS public.facility_bed_occupancy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    bed_type VARCHAR(30) NOT NULL,
    occupancy_date DATE NOT NULL,
    occupancy INT NOT NULL,
    facility_occupancy INT NOT NULL,
    flagged BOOLEAN DEFAULT FALSE,
   -- claim_ids JSON, -- Created a separate table facility_bed_occupancy_claim
    created_by VARCHAR(255),
    created_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT fk_facility_provider FOREIGN KEY (provider_id) REFERENCES public.provider(id) ON DELETE CASCADE
);

-- Indexes for faster search
CREATE INDEX IF NOT EXISTS idx_facility_bed_type ON public.facility_bed_occupancy (bed_type);
CREATE INDEX IF NOT EXISTS idx_facility_occupancy_date ON public.facility_bed_occupancy (occupancy_date);
CREATE INDEX IF NOT EXISTS idx_facility_provider_id ON public.facility_bed_occupancy (provider_id);
