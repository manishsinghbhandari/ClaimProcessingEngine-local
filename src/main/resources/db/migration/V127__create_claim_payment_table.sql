-- Create claim_payment table for tracking fund-type-level payment breakdowns per claim
CREATE TABLE IF NOT EXISTS public.claim_payment
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_by                VARCHAR(255),
    created_date              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by          VARCHAR(255),
    last_modified_date        TIMESTAMP(6),
    claim_id                  UUID NOT NULL,
    claimed_amount            NUMERIC(38, 2) NOT NULL,
    facility_payable_amount   NUMERIC(38, 2) NOT NULL,
    fund_type                 VARCHAR(255) NOT NULL,
    system_utilization_amount NUMERIC(38, 2) NOT NULL,
    CONSTRAINT claim_payment_pkey PRIMARY KEY (id),
    CONSTRAINT fk_claim_payment_claim_id FOREIGN KEY (claim_id)
        REFERENCES public.claims (claim_id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT claim_payment_fund_type_check CHECK (
        fund_type IN ('SHIF', 'ECCIF', 'PMSF')
    )
);

-- Add unique constraint on (claim_id, fund_type) to support saveOrUpdate lookups
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uk_claim_payment_claim_id_fund_type'
    ) THEN
        ALTER TABLE public.claim_payment
            ADD CONSTRAINT uk_claim_payment_claim_id_fund_type UNIQUE (claim_id, fund_type);
    END IF;
END $$;

-- Add index on claim_id for query performance
CREATE INDEX IF NOT EXISTS idx_claim_payment_claim_id ON public.claim_payment (claim_id);
