CREATE TABLE IF NOT EXISTS public.intervention_duration (
    id int8 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code varchar(255) NOT NULL,
    description varchar(255) NULL,
    duration int4 NOT NULL,
    "operator" varchar(255) NOT NULL,
    created_date TIMESTAMP DEFAULT NOW() NOT NULL,
    created_by VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
    last_modified_date TIMESTAMP DEFAULT NOW() NOT NULL,
    last_modified_by VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL
        CONSTRAINT intervention_duration_operator_check CHECK (
                operator IN ('==', '!=', '>', '<', '>=', '<=')),
    CONSTRAINT intervention_duration_pkey PRIMARY KEY (id)
);