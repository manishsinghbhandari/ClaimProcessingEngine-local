CREATE TABLE IF NOT EXISTS public.claim_ai_notes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        claim_id UUID NOT NULL,
        notes JSONB NULL,
        user_review JSONB NULL,
        overall_notes TEXT NULL,
        status VARCHAR(50) NOT NULL DEFAULT 'SENT',
        created_by VARCHAR(255) NULL,
    	created_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    	last_modified_by VARCHAR(255) NULL,
    	last_modified_date timestamp NULL,

    	CONSTRAINT fk_claim_notes_claim FOREIGN KEY (claim_id) REFERENCES public.claims(claim_id) ON DELETE RESTRICT,
    	CONSTRAINT valid_status CHECK (status IN ('SENT', 'FAILED', 'PROCESSED'))
);

-- Index for faster lookups
CREATE INDEX IF NOT EXISTS idx_claim_ai_notes_claim_id ON public.claim_ai_notes (claim_id);
CREATE INDEX IF NOT EXISTS idx_claim_ai_notes_status ON claim_ai_notes (status);

