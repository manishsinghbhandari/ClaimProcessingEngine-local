-- Create claim_ai_trigger table for managing AI trigger configurations
CREATE TABLE IF NOT EXISTS public.claim_ai_trigger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package VARCHAR(255) NOT NULL,
    intervention_code VARCHAR(100) NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    last_processed_claim_id BIGINT NULL,
    processed_claims_count INT NOT NULL DEFAULT 0,
    ai_url VARCHAR(255) NULL,
    created_by VARCHAR(100) NULL,
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(100) NULL,
    last_modified_date TIMESTAMP NULL,
    
    CONSTRAINT valid_trigger_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'FAILED'))
);

-- Create indexes for claim_ai_trigger table
CREATE INDEX IF NOT EXISTS idx_claim_ai_trigger_status ON public.claim_ai_trigger (status);
CREATE INDEX IF NOT EXISTS idx_claim_ai_trigger_intervention_dates 
    ON public.claim_ai_trigger (intervention_code, start_date, end_date);
