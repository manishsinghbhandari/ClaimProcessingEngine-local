CREATE TABLE IF NOT EXISTS public.claim_status_transition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by varchar(255) NULL,
    created_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_modified_by varchar(255) NULL,
    last_modified_date timestamp(6) NULL,
    use varchar(20) NULL,
    status varchar(255) NOT NULL,
    allowed_status varchar(255) NOT NULL,
    active boolean NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_claim_status_transition_active
ON claim_status_transition(status, allowed_status, use)
WHERE active = TRUE;