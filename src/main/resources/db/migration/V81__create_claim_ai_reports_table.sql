CREATE TABLE IF NOT EXISTS public.claim_ai_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id UUID NOT NULL,
    trigger_id BIGINT NULL,
    notes TEXT NULL,
    overall_notes TEXT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    scores DECIMAL(5,2) NULL,
    created_by VARCHAR(100) NULL,
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(100) NULL,
    last_modified_date TIMESTAMP NULL,
    
    CONSTRAINT fk_claim_ai_reports_claim FOREIGN KEY (claim_id) 
        REFERENCES public.claims(claim_id) ON DELETE RESTRICT,
    CONSTRAINT fk_claim_ai_reports_trigger FOREIGN KEY (trigger_id) 
        REFERENCES public.claim_ai_trigger(id) ON DELETE SET NULL,
    CONSTRAINT valid_report_status CHECK (status IN ('PENDING', 'REVIEWED', 'FLAGGED', 'SUCCESS'))
);

-- Create indexes for claim_ai_reports table
CREATE INDEX IF NOT EXISTS idx_claim_ai_reports_claim_id ON public.claim_ai_reports (claim_id);
CREATE INDEX IF NOT EXISTS idx_claim_ai_reports_trigger_id ON public.claim_ai_reports (trigger_id);
CREATE INDEX IF NOT EXISTS idx_claim_ai_reports_status ON public.claim_ai_reports (status);
