-- 1. Create ai_validation table
CREATE TABLE IF NOT EXISTS public.ai_validation (
    id BIGSERIAL PRIMARY KEY,
    validation_key VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    version INT NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    effective_date_from TIMESTAMP,
    effective_date_to TIMESTAMP,
    created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    last_modified_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(255)
);

-- 2. Create ai_validation_score table (ElementCollection)
CREATE TABLE IF NOT EXISTS public.ai_validation_score (
    ai_validation_id BIGINT NOT NULL,
    min_score DOUBLE PRECISION NOT NULL,
    max_score DOUBLE PRECISION NOT NULL,
    message VARCHAR(1000) NOT NULL,
    decision VARCHAR(50) NOT NULL,
    CONSTRAINT fk_ai_validation_score_validation_id
        FOREIGN KEY (ai_validation_id)
        REFERENCES public.ai_validation (id)
        ON DELETE CASCADE
);

-- 3. Create ai_validation_mapping table (Many-to-Many with benefits_master)
CREATE TABLE IF NOT EXISTS public.ai_validation_mapping (
