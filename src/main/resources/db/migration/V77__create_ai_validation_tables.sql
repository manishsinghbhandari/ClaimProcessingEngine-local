        ON DELETE CASCADE,
    CONSTRAINT fk_ai_validation_mapping_validation
        FOREIGN KEY (ai_validation_id)
        REFERENCES public.ai_validation (id)
        ON DELETE CASCADE
);

-- 4. Create ai_validation_log table (for version tracking & audit logs)
CREATE TABLE IF NOT EXISTS public.ai_validation_log (
