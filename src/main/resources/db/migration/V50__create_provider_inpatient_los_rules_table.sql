-- Table: public.intervention_inpatient_los_rules

CREATE TABLE IF NOT EXISTS public.intervention_inpatient_los_rules (
	    id int8 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        package_master_id INT NOT NULL,
        "level" varchar(10) NOT NULL,
        ownership varchar(255) DEFAULT 'ALL' NOT NULL,
        duration int4 NOT NULL,
        "operator" varchar(255) NOT NULL,
        action_status varchar(50) NOT NULL,
        created_date TIMESTAMP DEFAULT NOW() NOT NULL,
        created_by VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
        last_modified_date TIMESTAMP DEFAULT NOW() NOT NULL,
        last_modified_by VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL
            CONSTRAINT intervention_duration_operator_check CHECK (
                    operator IN ('==', '!=', '>', '<', '>=', '<='))
);


CREATE INDEX IF NOT EXISTS idx_package_master_id ON public.intervention_inpatient_los_rules USING btree (package_master_id) TABLESPACE pg_default;

