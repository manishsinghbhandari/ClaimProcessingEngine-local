CREATE TABLE IF NOT EXISTS public.surveillance_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        claim_id UUID NOT NULL,
        status VARCHAR(50) NOT NULL,
        reason TEXT NULL,
        created_by VARCHAR(255) NOT NULL,
    	created_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    	last_modified_by VARCHAR(255) NULL,
        last_modified_date TIMESTAMP NULL,

    	CONSTRAINT fk_surveillance_log_claim FOREIGN KEY (claim_id) REFERENCES public.claims(claim_id) ON DELETE RESTRICT
);

-- Index for faster lookups
CREATE INDEX IF NOT EXISTS idx_surveillance_log_claim_id ON public.surveillance_log (claim_id);
CREATE INDEX IF NOT EXISTS idx_surveillance_log_status ON surveillance_log (status);

