CREATE TABLE IF NOT EXISTS public.facility_bed_occupancy_claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id UUID NOT NULL,
    facility_bed_occupancy_id BIGINT NOT NULL,

        created_by varchar(255) NULL,
    	created_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    	last_modified_by varchar(255) NULL,
    	last_modified_date timestamp NULL,

    CONSTRAINT fk_occupancy_claim FOREIGN KEY (facility_bed_occupancy_id)
        REFERENCES public.facility_bed_occupancy(id) ON DELETE RESTRICT,

    CONSTRAINT unique_occupancy_claim UNIQUE(facility_bed_occupancy_id, claim_id)
);


-- Index on foreign key column
CREATE INDEX IF NOT EXISTS idx_occupancy_claim_occupancy_id
    ON public.facility_bed_occupancy_claim(facility_bed_occupancy_id);

-- Optional: Index on claim_id for faster direct lookups
CREATE INDEX IF NOT EXISTS idx_occupancy_claim_claim_id
    ON public.facility_bed_occupancy_claim(claim_id);




